// Packs the static site (index.html + assets/) into a single Cloudflare Worker script.
// Usage: node deploy/build-worker.mjs   (from the adal-price folder)
// Output: deploy/.build/worker.mjs — deploy it with `npx wrangler deploy -c deploy/wrangler.jsonc`.
import { readFileSync, readdirSync, statSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'deploy', '.build');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.txt': 'text/plain; charset=utf-8',
};
const TEXT = new Set(['.html', '.css', '.js', '.svg', '.txt']);
// Source images kept in the repo but not referenced by the page.
const SKIP = new Set(['assets/img/logo-mark.png']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = ['index.html', ...walk(join(root, 'assets')).map((p) => relative(root, p))]
  .map((p) => p.split('\\').join('/'))
  .filter((p) => !SKIP.has(p) && TYPES[extname(p)]);

const entries = files.map((p) => {
  const ext = extname(p);
  const buf = readFileSync(join(root, p));
  return {
    path: '/' + p,
    type: TYPES[ext],
    text: TEXT.has(ext),
    body: TEXT.has(ext) ? buf.toString('utf8') : buf.toString('base64'),
    etag: '"' + buf.length.toString(36) + '-' + hash(buf) + '"',
  };
});

function hash(buf) {
  let h = 2166136261;
  for (const b of buf) { h ^= b; h = Math.imul(h, 16777619) >>> 0; }
  return h.toString(36);
}

const worker = `// Generated by deploy/build-worker.mjs — do not edit by hand.
const FILES = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.path, { t: e.type, x: e.text, b: e.body, e: e.etag }])))};
const decoded = new Map();

function body(path, f) {
  if (f.x) return f.b;
  let bytes = decoded.get(path);
  if (!bytes) {
    const bin = atob(f.b);
    bytes = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    decoded.set(path, bytes);
  }
  return bytes;
}

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
    }
    let path = decodeURIComponent(url.pathname);
    if (path === '/' || path === '') path = '/index.html';
    const f = FILES[path];
    const headers = new Headers({
      'X-Content-Type-Options': 'nosniff',
      'Referrer-Policy': 'strict-origin-when-cross-origin',
    });
    // Preview address on workers.dev is kept out of search engines; a custom domain is indexed normally.
    if (url.hostname.endsWith('.workers.dev')) headers.set('X-Robots-Tag', 'noindex');
    if (!f) {
      headers.set('Content-Type', 'text/html; charset=utf-8');
      return new Response('<!doctype html><meta charset="utf-8"><title>Страница не найдена</title><p style="font-family:sans-serif">Страница не найдена. <a href="/">На главную ADAL PRICE</a></p>', { status: 404, headers });
    }
    headers.set('Content-Type', f.t);
    headers.set('ETag', f.e);
    headers.set('Cache-Control', path === '/index.html' ? 'public, max-age=0, must-revalidate' : 'public, max-age=3600');
    if (request.headers.get('If-None-Match') === f.e) return new Response(null, { status: 304, headers });
    return new Response(request.method === 'HEAD' ? null : body(path, f), { headers });
  },
};
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'worker.mjs'), worker);
console.log(`Packed ${entries.length} files into deploy/.build/worker.mjs (${(worker.length / 1024).toFixed(0)} KB)`);
