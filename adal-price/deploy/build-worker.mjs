// Packs the static site (index.html + assets/) into one Cloudflare Worker.
// Text files are inlined as strings; images are copied next to the script and
// imported as binary "Data" modules (see rules in wrangler.jsonc), so serving
// them costs no decoding work at request time.
// Usage: node deploy/build-worker.mjs   (from the adal-price folder)
// Output: deploy/.build/ — deploy it with `npx wrangler deploy -c deploy/wrangler.jsonc`.
import { readFileSync, readdirSync, statSync, mkdirSync, writeFileSync, rmSync, copyFileSync } from 'node:fs';
import { join, relative, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'deploy', '.build');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.txt': 'text/plain; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.webp': 'image/webp',
  '.ico': 'image/x-icon',
};
const TEXT = new Set(['.html', '.css', '.js', '.svg', '.txt']);
// Source images kept in the repo but not referenced by the page.
const SKIP = new Set(['assets/img/logo-mark.png']);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

function hash(buf) {
  let h = 2166136261;
  for (const b of buf) { h ^= b; h = Math.imul(h, 16777619) >>> 0; }
  return h.toString(36);
}

const files = ['index.html', ...walk(join(root, 'assets')).map((p) => relative(root, p))]
  .map((p) => p.split('\\').join('/'))
  .filter((p) => !SKIP.has(p) && TYPES[extname(p)]);

rmSync(outDir, { recursive: true, force: true });
mkdirSync(join(outDir, 'bin'), { recursive: true });

const imports = [];
const table = [];
files.forEach((p, i) => {
  const ext = extname(p);
  const buf = readFileSync(join(root, p));
  const etag = JSON.stringify('"' + buf.length.toString(36) + '-' + hash(buf) + '"');
  const meta = `t: ${JSON.stringify(TYPES[ext])}, e: ${etag}`;
  if (TEXT.has(ext)) {
    table.push(`  ${JSON.stringify('/' + p)}: { ${meta}, b: ${JSON.stringify(buf.toString('utf8'))} },`);
  } else {
    const name = `f${i}${ext}`;
    copyFileSync(join(root, p), join(outDir, 'bin', name));
    imports.push(`import f${i} from './bin/${name}';`);
    table.push(`  ${JSON.stringify('/' + p)}: { ${meta}, b: f${i}, bin: true },`);
  }
});

const worker = `// Generated by deploy/build-worker.mjs — do not edit by hand.
${imports.join('\n')}

const FILES = {
${table.join('\n')}
};

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      return new Response('Method not allowed', { status: 405, headers: { Allow: 'GET, HEAD' } });
    }
    let path = url.pathname;
    try { path = decodeURIComponent(path); } catch (e) { /* keep raw path */ }
    if (path === '/' || path === '') path = '/index.html';
    const f = Object.prototype.hasOwnProperty.call(FILES, path) ? FILES[path] : null;
    const headers = new Headers({
      'X-Content-Type-Options': 'nosniff',
      'Referrer-Policy': 'strict-origin-when-cross-origin',
    });
    // Preview address on workers.dev is kept out of search engines; a custom domain is indexed normally.
    if (url.hostname.endsWith('.workers.dev')) headers.set('X-Robots-Tag', 'noindex');
    if (!f) {
      headers.set('Content-Type', 'text/html; charset=utf-8');
      return new Response('<!doctype html><meta charset="utf-8"><title>Страница не найдена</title><p style="font-family:sans-serif">Страница не найдена. <a href="/">На главную ADAL PRICE</a></p>', { status: 404, headers });
    }
    headers.set('Content-Type', f.t);
    headers.set('ETag', f.e);
    headers.set('Cache-Control', path === '/index.html' ? 'public, max-age=0, must-revalidate' : 'public, max-age=3600');
    if (request.headers.get('If-None-Match') === f.e) return new Response(null, { status: 304, headers });
    if (request.method === 'HEAD') return new Response(null, { headers });
    // Copy binary data so the shared module buffer is never handed off to a response.
    return new Response(f.bin ? f.b.slice(0) : f.b, { headers });
  },
};
`;

writeFileSync(join(outDir, 'worker.mjs'), worker);
const binCount = imports.length;
console.log(`Packed ${files.length} files (${files.length - binCount} inline text, ${binCount} binary modules) into deploy/.build/ (script ${(worker.length / 1024).toFixed(0)} KB)`);
